export function computeMetrics(merchants: Merchant[]): DashboardMetrics {
  const now = new Date();
  const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1).toISOString();
  return {
    totalMerchants: merchants.length,
    needsReview: merchants.filter(m => m.status === 'needs_review' || m.status === 'extraction_failed').length,
    readyForSubmission: merchants.filter(m => m.status === 'ready_for_submission').length,
    followUpsDue: merchants.filter(m => m.status === 'incomplete' || m.status === 'extraction_failed').length,
    submittedThisMonth: merchants.filter(m => m.status === 'submitted' && m.updatedAt >= startOfMonth).length,
  };
}
